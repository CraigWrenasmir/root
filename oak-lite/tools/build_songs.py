#!/usr/bin/env python3
"""Cut the three Oak Lite clips + trimmed charts from a Live at The Oak checkout.

  python3 tools/build_songs.py /path/to/Live-at-The-Oak

Writes audio/<slug>.mp3 (short faded clips) and oak-lite-songs.js.
Clip windows start/end on bar lines so the beat grid stays intact.
"""
import json, subprocess, sys, os

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
# slug, title, first bar of the clip, bars in the clip
PICKS = [
    ("rdst-gm",    "Rdst Gm",    20, 60),   # skips the sparse intro, lands as the beat arrives
    ("crafluropi", "Crafluropi",  0, 46),
    ("mabon",      "Mabon",       0, 48),
]
FADE_OUT, TAIL = 3.0, 1.5      # seconds; no notes in the last TAIL of the clip

songs = []
for slug, title, bar0, bars in PICKS:
    charts = {}
    for diff, suffix in (("standard", ""), ("hard", "-hard")):
        c = json.load(open(f"{SRC}/charts/{slug}{suffix}.json"))
        bar = 4 * 60.0 / c["bpm"]
        # start a hair before the bar line so the downbeat isn't clipped
        start = max(0.0, c["beatOffset"] + bar0 * bar - 0.25) if bar0 else 0.0
        length = round(c["beatOffset"] + (bar0 + bars) * bar - start, 3)
        fade_in = 1.0 if bar0 else 0.0
        notes = []
        for n in c["notes"]:
            t = n["t"] - start
            if t < fade_in * 0.5 + 0.05 or t > length - TAIL:
                continue
            ln = min(n.get("len", 0) or 0, length - TAIL - t)
            notes.append([round(t, 3), n["lane"]] + ([round(ln, 3)] if ln > 0.2 else []))
        charts[diff] = notes
    songs.append({"slug": slug, "title": title, "bpm": c["bpm"],
                  "beatOffset": round((c["beatOffset"] - start) % (60.0 / c["bpm"]), 4),
                  "duration": length, "charts": charts})
    af = (f"afade=t=in:d={fade_in}," if fade_in else "") + \
         f"afade=t=out:st={length - FADE_OUT}:d={FADE_OUT}"
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-ss", f"{start:.4f}", "-t", f"{length:.3f}",
                    "-i", f"{SRC}/audio/{slug}.mp3", "-af", af, "-ac", "2", "-ar", "44100",
                    "-c:a", "libmp3lame", "-b:a", "128k", "-map_metadata", "-1",
                    f"{OUT}/audio/{slug}.mp3"], check=True)
    print(slug, f"start={start:.3f}s len={length}s",
          {d: len(v) for d, v in charts.items()})

with open(f"{OUT}/oak-lite-songs.js", "w") as f:
    f.write("/* Generated by tools/build_songs.py - notes are [time, lane, holdLength?] */\n")
    f.write("window.OakLiteSongs = " + json.dumps(songs, separators=(",", ":")) + ";\n")
